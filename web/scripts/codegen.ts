import { glob, mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { codegen } from '@graphql-codegen/core';
import { plugin as operations } from '@graphql-codegen/typescript-operations';
import { plugin as typedDocumentNode } from '@graphql-codegen/typed-document-node';
import { concatAST, parse, separateOperations, validate } from 'graphql';
import { addTypenameToDocument } from '@apollo/client/utilities';
import { graphqlOperationNames } from '@napl/contracts';
import { schema } from '../../api/routes/graphql/schema.ts';

const root = path.resolve(import.meta.dirname, '../..');
const outputPath = path.resolve(root, 'web/src/api/generated/graphql.ts');
const serverOutputPath = path.resolve(root, 'api/routes/graphql/generated/operations.ts');
const check = process.argv.includes('--check');
const allDocumentPaths = await Array.fromAsync(glob(path.resolve(root, 'api/routes/graphql/operations/*.graphql')));
const documentPaths = allDocumentPaths
  .toSorted((left, right) => left.localeCompare(right));
const documents = await Promise.all(documentPaths.map(async location => ({
  location,
  document: addTypenameToDocument(parse(await readFile(location, 'utf8'), { noLocation: true })),
})));
const documentErrors = validate(schema, concatAST(documents.map(({ document }) => document)));
if (documentErrors.length > 0) throw new Error(documentErrors.map(error => error.message).join('\n'));

const generated = await codegen({
  filename: outputPath,
  schema,
  documents,
  config: {
    avoidOptionals: true,
    maybeValue: 'T | null',
    scalars: { JSON: 'unknown' },
    enumsAsTypes: true,
    useTypeImports: true,
    documentMode: 'documentNode',
  },
  plugins: [
    { 'typescript-operations': {} },
    { 'typed-document-node': {} },
  ],
  pluginMap: {
    'typescript-operations': { plugin: operations },
    'typed-document-node': { plugin: typedDocumentNode },
  },
});
const trustedOperations = separateOperations(concatAST(documents.map(({ document }) => document)));
if (Object.keys(trustedOperations).toSorted((left, right) => left.localeCompare(right)).join(',') !== [...graphqlOperationNames].toSorted((left, right) => left.localeCompare(right)).join(',')) {
  throw new Error('Trusted GraphQL operations must match the allowed operation names.');
}
const serverOutput = `// Generated by web/scripts/codegen.ts.
import type { DocumentNode } from 'graphql';
import type { GraphQLOperationName } from '@napl/contracts';

export const trustedOperations = ${JSON.stringify(trustedOperations)} as unknown as Record<GraphQLOperationName, DocumentNode>;
`;
for (const [filename, output] of [[outputPath, generated], [serverOutputPath, serverOutput]]) {
  if (check) {
    let current;
    try { current = await readFile(filename!, 'utf8'); } catch { current = undefined; }
    if (current !== output) {
      console.error('Generated GraphQL documents are stale. Run pnpm run gql:generate.');
      process.exitCode = 1;
    }
  } else {
    await mkdir(path.dirname(filename!), { recursive: true });
    await writeFile(filename!, output!);
  }
}
